#!/usr/bin/env python3
"""Fill the generated block of EVAL.md from the saved results, so the numbers cannot drift.

EVAL.md keeps its prose by hand; everything between the two marker comments is produced here from
eval/results/{before_fixes,after_fixes}/ and eval/data/award_label_evidence.json. tests/test_eval_data.py
fails if EVAL.md no longer matches this output.

Usage: python eval/render_eval_md.py        # rewrite the block in EVAL.md
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BEGIN, END = "<!-- results:begin (generated by eval/render_eval_md.py; do not edit) -->", "<!-- results:end -->"
MODES = (("bm25", "BM25"), ("semantic", "Semantic"), ("hybrid", "Hybrid (RRF)"))


def load(path):
    return json.loads((ROOT / path).read_text())


def cwn(d):
    return f"{d['correct']} / {d['wrong']} / {d['no_answer']}"


def awards_table(summary, scope, title):
    """Overall (director AND verdict) by truth class, plus the director and verdict columns on their own."""
    a = summary["awards"][scope]
    lines = [f"**{title}**", "", "Cells are correct / wrong / no answer. A row is wrong overall if the director OR the verdict is wrong; "
             "it is correct overall only if both are correct.", "",
             "| Truth class (n films), overall | " + " | ".join(n for _, n in MODES) + " |", "|---|" + "---|" * len(MODES)]
    for t, note in (("won", ""), ("nominated", ""), ("no_win", " (never correct: the system has no \"no win\" output)")):
        n = a["semantic"]["by_truth"][t]["n"]
        lines.append(f"| {t} ({n}){note} | " + " | ".join(cwn(a[m]["by_truth"][t]["overall"]) for m, _ in MODES) + " |")
    lines.append(f"| **all ({a['n_films']})** | " + " | ".join(cwn(a[m]["overall"]) for m, _ in MODES) + " |")
    lines.append("| *all, if a name with extra text were accepted as correct* | " + " | ".join(cwn(a[m]["overall_if_malformed_accepted"]) for m, _ in MODES) + " |")
    cov = lambda m: a[m]["coverage_on_answerable_overall"]
    lines.append("| **coverage on answerable films** (overall correct ÷ answerable films) | " + " | ".join(
        f"{cov(m)['correct']}/{cov(m)['of']} answerable films = {cov(m)['ratio']:.2f}" for m, _ in MODES) + " |")
    lines += ["", "| Components (all %d films) | " % a["n_films"] + " | ".join(n for _, n in MODES) + " |", "|---|" + "---|" * len(MODES),
              "| Verdict only | " + " | ".join(cwn(a[m]["verdict"]) for m, _ in MODES) + " |",
              "| Director only (wrong includes malformed) | " + " | ".join(cwn(a[m]["director"]) for m, _ in MODES) + " |",
              "| of which malformed: the right name with extra text attached | " + " | ".join(str(a[m]["director"]["malformed"]) for m, _ in MODES) + " |"]
    cov_v = lambda m: a[m]["coverage_on_answerable_verdict"]
    lines.append("| Verdict-only coverage | " + " | ".join(f"{cov_v(m)['correct']}/{cov_v(m)['of']} answerable films = {cov_v(m)['ratio']:.2f}" for m, _ in MODES) + " |")
    mix = a["truth_mix"]
    which = "This split has" if scope != "all" else "These films include"
    lines += ["", f"{which} {mix['no_win']} of {a['n_films']} films with truth `no_win`, so it mostly measures abstention: "
              f"only {mix['won'] + mix['nominated']} films can be answered correctly."]
    return "\n".join(lines)


def wrong_overall(rows_path, scope):
    rows = [r for r in load(rows_path)["rows"] if scope == "all" or r["split"] == scope]
    out = []
    for m, name in MODES:
        items = []
        for r in rows:
            x = r["modes"][m]
            why = []
            if x["score"] == "wrong":
                why.append(f"verdict {x['verdict']}, truth {r['truth']}")
            if x["director_status"] in ("wrong", "malformed"):
                why.append(f"{x['director_status']} director \"{x['director_found'][:50]}\", expected {r['expected_director']}")
            if why:
                items.append(f"{r['film']} [{r['split']}] ({'; '.join(why)})")
        out.append(f"- {name}: " + ("; ".join(items) if items else "none"))
    return "\n".join(out)


def director_failures(rows_path):
    """Every film where some mode's director string is not exactly right, with the split and each mode's output."""
    rows = load(rows_path)["rows"]
    lines = ["| Film | Split | " + " | ".join(n for _, n in MODES) + " |", "|---|---|" + "---|" * len(MODES)]
    for r in rows:
        if all(r["modes"][m]["director_status"] == "correct" for m, _ in MODES):
            continue
        cells = []
        for m, _ in MODES:
            x = r["modes"][m]
            st = x["director_status"]
            cells.append("correct" if st == "correct" else "Unknown" if st == "no answer"
                         else f"**{st.upper()}**: \"{(x['director_found'] or '')[:46]}\"")
        lines.append(f"| {r['film']} | {r['split']} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def director_fix_section(before):
    """Before/after the director-detection fix, if its results exist. Always labelled not held out."""
    path = ROOT / "eval/results/after_director_fix/summary.json"
    if not path.exists():
        return []
    after = load("eval/results/after_director_fix/summary.json")
    splits = load("eval/data/splits.json")["awards"]
    where = {f: ("test" if f in splits["test"] else "dev") for f in ("Ed Wood (film)", "Romeo + Juliet", "Last Action Hero")}
    lines = ["### After the director-detection fix: NOT held out", "",
             "The fix was written while looking at these films ("
             + ", ".join(f"{f.replace(' (film)', '')}: {sp} split" for f, sp in where.items())
             + "), so every number in this section is **not held out**; it shows what the change did on films it was developed on, not how it behaves on unseen ones. "
             f"Retrieval results are {'identical' if before['retrieval'] == after['retrieval'] else 'DIFFERENT'} before and after.", ""]
    for scope, title in (("test", "test split (n=16)"), ("all", "all 26 films (dev + test)")):
        b, a = before["awards"][scope], after["awards"][scope]
        lines += [f"**Director fix, {title}** (cells: correct / wrong / no answer)", "",
                  "| | " + " | ".join(f"{n}: before" + " | " + f"{n}: after" for _, n in MODES) + " |", "|---|" + "---|---|" * len(MODES)]
        for label, key in (("Overall (director AND verdict, strict)", "overall"), ("Director only (wrong includes malformed)", "director"), ("Verdict only", "verdict")):
            lines.append(f"| {label} | " + " | ".join(f"{cwn(b[m][key])} | {cwn(a[m][key])}" for m, _ in MODES) + " |")
        lines.append("| Director strings that are the right name plus extra words | " + " | ".join(f"{b[m]['director']['malformed']} | {a[m]['director']['malformed']}" for m, _ in MODES) + " |")
        lines.append("")
    films = load("eval/results/after_director_fix/awards_results.json")["rows"]
    not_exact = [f"{r['film']} ({m})" for r in films for m, _ in MODES if r["modes"][m]["director_status"] != "correct"]
    lines += ["Director strings still not exactly right after the fix: " + (", ".join(not_exact) if not_exact else "none") + ".", ""]
    return lines


def render() -> str:
    before, after = load("eval/results/before_fixes/summary.json"), load("eval/results/after_fixes/summary.json")
    r = before["retrieval"]["test"]
    p = r["paired_recall@10"]
    retrieval = ["| Retrieval (n=%d) | recall@5 | recall@10 | all gold in top 10 (95%% interval) | MRR |" % r["n_questions"], "|---|---|---|---|---|"]
    for m, name in MODES:
        g = r[m]["all_gold@10"]
        retrieval.append(f"| {name} | {r[m]['recall@5']:.2f} | {r[m]['recall@10']:.2f} | {g['count']}/{g['of']} ({g['wilson95'][0]:.2f} to {g['wilson95'][1]:.2f}) | {r[m]['mrr']:.2f} |")
    sb, hs = p["semantic_vs_bm25"], p["hybrid_vs_semantic"]
    evidence = load("eval/data/award_label_evidence.json")["films"]
    ok = sum(e["status"].startswith("consistent") for e in evidence)
    manual = sum("manual" in e["status"] for e in evidence)
    unchanged = before["retrieval"] == after["retrieval"]
    block = [
        BEGIN, "",
        "### Held-out, before fixes", "",
        "From `eval/results/before_fixes/`. Nothing had been tuned on the test split at this point.", "",
        *retrieval, "",
        f"Paired on recall@10 (test): semantic beats BM25 on {sb['better']} of {r['n_questions']} questions and loses on {sb['worse']}; "
        f"hybrid beats semantic on {hs['better']} and loses on {hs['worse']} ({hs['tied']} tied), and has lower recall@5 "
        f"({r['hybrid']['recall@5']:.2f} vs {r['semantic']['recall@5']:.2f}). **There is no evidence that hybrid retrieval helps at n={r['n_questions']}.**", "",
        awards_table(before, "test", "Awards, test split, held-out, before fixes"), "",
        awards_table(before, "all", "Awards, all 26 films (dev + test), before fixes: descriptive, not a held-out estimate"), "",
        "### After fixes: test split no longer held out", "",
        "Two verdict faults were found on this test split and fixed (see below). The numbers here, from "
        "`eval/results/after_fixes/` (re-run on `main`), were produced **after** looking at this split, so they are **not held out** and say nothing about unseen films. "
        f"Retrieval results are {'identical' if unchanged else 'DIFFERENT'} before and after.", "",
        awards_table(after, "test", "Awards, test split, after fixes (not held out)"), "",
        awards_table(after, "all", "Awards, all 26 films (dev + test), after fixes: descriptive, not a held-out estimate"), "",
        "Wrong overall (director or verdict), after fixes:", "",
        "Test split:", "", wrong_overall("eval/results/after_fixes/awards_results.json", "test"), "",
        "All 26 films (dev + test):", "", wrong_overall("eval/results/after_fixes/awards_results.json", "all"), "",
        "Films where some method's director string is not exactly right (output per method):", "", director_failures("eval/results/after_fixes/awards_results.json"), "",
        *director_fix_section(after),
        f"Label sourcing check (`python eval/verify_award_labels.py`): {ok} of {len(evidence)} award rows pass; {manual} of them needed a manual reading of the passages.",
        "", END,
    ]
    return "\n".join(block)


def main() -> None:
    path = ROOT / "EVAL.md"
    text = path.read_text()
    a, b = text.index(BEGIN), text.index(END) + len(END)
    path.write_text(text[:a] + render() + text[b:])
    print("EVAL.md results block updated")


if __name__ == "__main__":
    main()
